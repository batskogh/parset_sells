"""Тести часових зрізів історії.

Головне, що тут перевіряється, — щоб сума набору не реагувала на розклад
парсингу: ані на кілька замірів за день, ані на пропущений день, ані на
товар, який з'явився в базі пізніше за інші.
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

from datetime import datetime, timezone

from app.core.timeline import (
    basket_series,
    daily_last,
    daily_values,
    days_between,
    fill_forward,
)

D = Decimal


def день(number: int) -> date:
    return date(2026, 9, number)


def test_кілька_замірів_за_добу_зводяться_до_останнього() -> None:
    series = daily_last([(день(1), D("100")), (день(1), D("90")), (день(2), D("80"))])
    assert series == {день(1): D("90"), день(2): D("80")}


def test_добові_ціни_одного_товару_беруть_останню_за_день() -> None:
    """Чотири обходи на добу мають дати одну ціну за добу, а не чотири."""
    момент = lambda д, г: datetime(2026, 9, д, г, 0, tzinfo=timezone.utc)
    значення = daily_values(
        [
            (момент(1, 0), D("100")),
            (момент(1, 6), D("100")),
            (момент(1, 12), D("95")),
            (момент(1, 18), D("90")),
            (момент(2, 0), D("80")),
        ]
    )
    assert значення == [D("90"), D("80")]


def test_добові_ціни_не_залежать_від_порядку_замірів() -> None:
    """З бази ціни приходять найновішими вперед — це не має міняти результат."""
    момент = lambda д, г: datetime(2026, 9, д, г, 0, tzinfo=timezone.utc)
    заміри = [(момент(1, 0), D("100")), (момент(1, 18), D("90")), (момент(2, 0), D("80"))]
    assert daily_values(заміри) == daily_values(reversed(заміри))


def test_доби_відрізка_включно_з_краями() -> None:
    assert days_between(день(1), день(3)) == [день(1), день(2), день(3)]
    assert days_between(день(3), день(1)) == []
    assert days_between(день(1), день(1)) == [день(1)]


def test_перенос_ціни_вперед_на_пропущені_дні() -> None:
    """Магазин був недоступний два дні — ціна вважається тією ж, що й була."""
    filled = fill_forward({день(1): D("100"), день(4): D("80")}, days_between(день(1), день(5)))
    assert filled == {
        день(1): D("100"),
        день(2): D("100"),
        день(3): D("100"),
        день(4): D("80"),
        день(5): D("80"),
    }


def test_до_першого_заміру_ціни_немає() -> None:
    """Назад ціну не домислюємо: тоді її просто не знали."""
    filled = fill_forward({день(3): D("100")}, days_between(день(1), день(4)))
    assert день(1) not in filled and день(2) not in filled
    assert filled[день(3)] == D("100")


def test_сума_набору_по_добах() -> None:
    totals = basket_series(
        {
            "чипси": [(день(1), D("74")), (день(2), D("74"))],
            "кава": [(день(1), D("200")), (день(2), D("180"))],
        }
    )
    assert totals == [(день(1), D("274")), (день(2), D("254"))]


def test_сума_не_стрибає_від_розкладу_парсингу() -> None:
    """Другий товар не парсився в день 2 — сума має лишитись повною."""
    totals = basket_series(
        {
            "чипси": [(день(1), D("74")), (день(2), D("70")), (день(3), D("70"))],
            "кава": [(день(1), D("200")), (день(3), D("200"))],
        }
    )
    assert totals == [(день(1), D("274")), (день(2), D("270")), (день(3), D("270"))]


def test_поява_товару_не_виглядає_як_подорожчання() -> None:
    """Ряд починається з дати, коли відомі всі товари набору."""
    totals = basket_series(
        {
            "давній": [(день(1), D("100")), (день(2), D("100")), (день(3), D("100"))],
            "новий": [(день(3), D("50"))],
        }
    )
    assert totals == [(день(3), D("150"))]


def test_можна_рахувати_з_неповного_набору() -> None:
    totals = basket_series(
        {
            "давній": [(день(1), D("100")), (день(2), D("100"))],
            "новий": [(день(2), D("50"))],
        },
        require_all=False,
    )
    assert totals == [(день(1), D("100")), (день(2), D("150"))]


def test_порожній_набір() -> None:
    assert basket_series({}) == []
    assert basket_series({"без історії": []}) == []
