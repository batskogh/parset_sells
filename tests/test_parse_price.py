"""Тести розбору ціни.

Ціна — те місце, де тиха помилка найдорожча: неправильно розібране число не
падає, а лягає в історію й потім керує рішенням про знижку. Тому тут не лише
щасливі формати, а й сміття, яке трапляється поруч із ціною на живих сторінках.
"""

from __future__ import annotations

from decimal import Decimal

import pytest

from app.parsers.utils import parse_price


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        # формати, зняті з живих сторінок проєкту
        ("74 ₴", "74.00"),                    # maudau, чипси
        ("39 199 ₴", "39199.00"),             # citrus, відеокарта
        ("1 959 ₴", "1959.00"),               # citrus, рядок кешбеку
        ("£51.77", "51.77"),                  # books.toscrape
        ("750", "750.00"),                    # staff, число з ld+json
        # роздільники тисяч і дробу
        ("1 299,00 грн", "1299.00"),          # український запис
        ("1,299.00", "1299.00"),              # англійський
        ("1.299,50 zł", "1299.50"),           # польський
        ("12999₴", "12999.00"),               # без пробілів
        ("12,5", "12.50"),
        ("12.5", "12.50"),
        (".99", "0.99"),
        ("99.", "99.00"),
        ("0", "0.00"),
    ],
)
def test_розбирає_живі_формати(raw: str, expected: str) -> None:
    assert parse_price(raw) == Decimal(expected)


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        # три цифри після одного роздільника — це тисячі, а не копійки
        ("1.299", "1299.00"),
        ("1.234.567", "1234567.00"),
        ("9.999", "9999.00"),
        # ...але не тоді, коли ціла частина нульова: 0.750 — це 75 копійок
        ("0.750", "0.75"),
        ("0,750", "0.75"),
    ],
)
def test_три_цифри_після_крапки_це_тисячі(raw: str, expected: str) -> None:
    assert parse_price(raw) == Decimal(expected)


@pytest.mark.parametrize(
    "raw",
    [
        None,
        "",
        "   ",
        "Ціна не вказана",
        "уточнюйте",
        "1 299,00 - 2 500,00",   # діапазон: незрозуміло, яку з двох брати
        "--5",
        "9" * 30,               # довше за точність Decimal — колись кидало виняток
    ],
)
def test_повертає_none_коли_ціни_немає(raw: str | None) -> None:
    assert parse_price(raw) is None


def test_відкидає_відємну_ціну() -> None:
    """Від'ємної ціни не буває — це або збій розбору, або чуже число поруч."""
    assert parse_price("-50") is None
    assert parse_price("-1 299,00 грн") is None


def test_бере_перше_число_з_тексту_з_приміткою() -> None:
    """«від 2 614 ₴» — розстрочка на сторінці citrus поруч зі справжньою ціною."""
    assert parse_price("від 2 614 ₴") == Decimal("2614.00")


def test_приймає_число_а_не_лише_текст() -> None:
    """У ld+json ціна приходить числом: 750 у staff, 39199 у citrus."""
    assert parse_price(750) == Decimal("750.00")
    assert parse_price(39199) == Decimal("39199.00")
    assert parse_price(74.5) == Decimal("74.50")


def test_округлює_до_копійок() -> None:
    assert parse_price("74.4999") == Decimal("74.50")
    assert parse_price("74,4949") == Decimal("74.49")


def test_завжди_два_знаки_після_коми() -> None:
    """Однаковий масштаб важливий: ціни потім порівнюються між собою."""
    assert str(parse_price("74")) == "74.00"
    assert str(parse_price("74.5")) == "74.50"
