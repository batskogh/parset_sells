def shop_demand_list(items: list) -> str:
    """Накопичений попит на магазини, яких парсер не знає — власнику.

    Сенс списку в порядку: зверху те, що просять найчастіше. Саме звідти й
    беруться наступні магазини, замість «здається, хтось колись просив».
    """
    if not items:
        return (
            "Заявок на нові магазини немає.\n\n"
            "Вони з'являються самі: щоразу, коли хтось надсилає посилання на "
            "магазин, якого я не вмію читати."
        )

    рядки = ["<b>Просять магазини, яких я не знаю</b>", ""]
    for номер, item in enumerate(items, start=1):
        рядки.append(
            f"{номер}. <b>{escape(item.host)}</b> — "
            f"спроб {item.times}, різних людей {item.people}"
        )
    return "\n".join(рядки)


