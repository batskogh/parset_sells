"""Тексти бота окремо від хендлерів.

Винесені навмисно: так їх видно всі одразу (легше тримати один тон), і так
їх можна перевіряти тестами, не піднімаючи Telegram.
"""

from __future__ import annotations

BOT_COMMANDS: dict[str, str] = {
    "start": "почати роботу",
    "help": "що вміє бот",
    "stop": "припинити сповіщення",
}


def welcome(first_name: str | None, *, returning: bool = False) -> str:
    звертання = f", {first_name}" if first_name else ""
    якщо_повернувся = "Радий знову бачити" if returning else "Вітаю"
    return (
        f"{якщо_повернувся}{звертання}!\n\n"
        "Я стежу за цінами й пишу, коли вони справді падають.\n\n"
        "«Справді» — це нижче звичної ціни товару, порахованої за всією його "
        "історією, а не нижче перекресленої ціни на сайті: її магазини "
        "накручують.\n\n"
        "Надішли посилання на товар — почну стежити.\n"
        "Команда /help покаже решту."
    )


def help_text() -> str:
    return (
        "Як я працюю:\n\n"
        "• надішли посилання на товар — додам його до свого списку;\n"
        "• щодня перевірятиму ціну й збиратиму історію;\n"
        "• коли ціна впаде помітно нижче звичної — напишу.\n\n"
        "Про одну знижку кажу один раз, а не щодня, доки вона триває.\n\n"
        "Команди:\n"
        "/help — це повідомлення\n"
        "/stop — припинити сповіщення (список лишиться)"
    )


def stopped() -> str:
    return (
        "Сповіщення вимкнено. Список товарів лишається на місці — "
        "надішли /start, щоб знову їх отримувати."
    )
