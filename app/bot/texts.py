UPDATE_HEADINGS: dict[str, str] = {
    "updated": "Сервер оновився",
    "rolled_back": "Оновлення відкочено",
    "failed": "Оновлення не вдалося",
}


def update_report(
    *,
    status: str,
    branch: str = "",
    revision: str = "",
    commits: list[str] | None = None,
    details: str = "",
) -> str:
    """Звіт про спробу оновити код на сервері.

    Пишеться власнику після кожного оновлення, бо машина стоїть на горищі:
    єдиний спосіб дізнатися, що сталося з кодом після `git push`, — щоб вона
    сама про це сказала. Мовчання тут читалося б як «усе гаразд», а це
    найгірше можливе значення для мовчання.

    Три результати, і різниця між ними принципова. `rolled_back` — тести
    впали, код повернуто на попередній коміт, служби працюють на старому й
    робочому. `failed` — зламалось саме оновлення (не витяглось, не стали
    залежності, не пройшла міграція), і стан машини треба подивитись очима.
    """
    заголовок = UPDATE_HEADINGS.get(status, "Оновлення")
    рядки = [f"<b>{заголовок}</b>", ""]

    if branch:
        рядки.append(f"Гілка: {escape(branch)}")
    if revision:
        рядки.append(f"Версія: <code>{escape(revision)}</code>")

    for заголовок_коміта in (commits or [])[:10]:
        рядки.append(f"• {escape(заголовок_коміта[:100])}")

    if status == "rolled_back":
        рядки += [
            "",
            "Тести на новому коді не пройшли, тож код повернуто на попередній "
            "коміт. Служби працюють на старій версії — вона робоча.",
        ]
    elif status == "failed":
        рядки += ["", "Стан машини варто подивитись очима: сюди дійшло не все."]

    if details:
        рядки += ["", f"<pre>{escape(details[:1500])}</pre>"]

    return "\n".join(рядки)


# ------------------------------------------------------------- сповіщення


def discount_alert(
    *,
    name: str,
    url: str,
    price: str,
    currency: str,
    usual: str,
    drop_percent: str,
    saving: str,
    samples: int,
    in_stock: bool = True,
) -> str:
    """Сповіщення про знижку.

    Головне — не сам відсоток, а від чого він рахується: людина має бачити
    звичну ціну й кількість замірів, щоб зрозуміти, чому це не чергова
    перекреслена ціна з сайту.
    """
    назва = escape(name[:90])
    адреса = escape(url, quote=True)
    рядки = [
        f"<b>{назва}</b>",
        "",
        f"Ціна: <b>{price} {currency}</b> (було звично {usual})",
        f"Дешевше на {drop_percent}% — це {saving} {currency}",
        "",
        f"Звичну ціну пораховано за {samples} днями спостережень.",
    ]
    if not in_stock:
        рядки.append("Але зараз товару немає в наявності.")
    рядки.append("")
    рядки.append(f'<a href="{адреса}">Відкрити в магазині</a>')
    return "\n".join(рядки)
